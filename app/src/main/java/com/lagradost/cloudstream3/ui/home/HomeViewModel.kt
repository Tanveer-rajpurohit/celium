    private fun loadResumeWatching() = viewModelScope.launchSafe {
        val resumeWatchingResult = getResumeWatching()
        if (isLayout(TV) && resumeWatchingResult != null && Build.VERSION.SDK_INT >= Build.VERSION_CODES.O) {
            ioSafe {
                // this WILL crash on non tvs, so keep this inside a try catch
                activity?.addProgramsToContinueWatching(resumeWatchingResult)
            }
        }
        resumeWatchingResult?.let {
            _resumeWatching.postValue(it)
        }
    }

    fun loadStoredData(preferredWatchStatus: Set<WatchType>?) = viewModelScope.launchSafe {
        val watchStatusIds = withContext(Dispatchers.IO) {
            getAllWatchStateIds()?.map { id ->
                Pair(id, getResultWatchState(id))
            }
        }?.distinctBy { it.first } ?: return@launchSafe

        val length = WatchType.entries.size
        val currentWatchTypes = mutableSetOf<WatchType>()

        for (watch in watchStatusIds) {
            currentWatchTypes.add(watch.second)
            if (currentWatchTypes.size >= length) {
                break
            }
        }

        currentWatchTypes.remove(WatchType.NONE)

        if (currentWatchTypes.size <= 0) {
            DataStoreHelper.homeBookmarkedList = intArrayOf()
            _availableWatchStatusTypes.postValue(setOf<WatchType>() to setOf())
            _bookmarks.postValue(Pair(false, ArrayList()))
            return@launchSafe
        }

        val watchPrefNotNull = preferredWatchStatus ?: EnumSet.of(currentWatchTypes.first())
        //if (currentWatchTypes.any { watchPrefNotNull.contains(it) }) watchPrefNotNull else listOf(currentWatchTypes.first())

        DataStoreHelper.homeBookmarkedList = watchPrefNotNull.map { it.internalId }.toIntArray()
        _availableWatchStatusTypes.postValue(

            watchPrefNotNull to
                    currentWatchTypes,

            )

        val list = withContext(Dispatchers.IO) {
            watchStatusIds.filter { watchPrefNotNull.contains(it.second) }
                .mapNotNull { getBookmarkedData(it.first) }
                .sortedBy { -it.latestUpdatedTime }
        }
        _bookmarks.postValue(Pair(true, list))
    }

    private var onGoingLoad: Job? = null
    private var isCurrentlyLoadingName: String? = null
    private var homeGeneration = 0
    private fun loadAndCancel(api: MainAPI, forceRefresh: Boolean = false) {
        homeGeneration++
        onGoingLoad?.cancel()
        addJob?.cancel()
        isCurrentlyLoadingName = api.name
        onGoingLoad = load(api, forceRefresh)
    }

    data class ExpandableHomepageList(
        var list: HomePageList,
        var currentPage: Int,
        var hasNext: Boolean,
    )

    private val expandable: MutableMap<String, ExpandableHomepageList> = mutableMapOf()
    private val _page =
        MutableLiveData<Resource<Map<String, ExpandableHomepageList>>>(Resource.Loading())
    val page: LiveData<Resource<Map<String, ExpandableHomepageList>>> = _page

    private val lock = mutableSetOf<Pair<Int, String>>()

    suspend fun expandAndReturn(name: String): ExpandableHomepageList? = withContext(Dispatchers.Main) {
        val source = repo ?: return@withContext null
        val current = expandable[name] ?: return@withContext null
        val generation = homeGeneration
        val request = generation to name
        if (!current.hasNext || !lock.add(request)) return@withContext null
        try {
            val nextPage = current.currentPage + 1
            val next = withContext(Dispatchers.IO) {
                source.waitForHomeDelay()
                val sectionIndex = if (source.api === DiscoveryProvider) {
                    DiscoveryProvider.sectionIndex(name, source.mainPage)
                } else source.mainPage.indexOfFirst { it.name == name }
                source.getMainPage(nextPage, sectionIndex)
            }
            if (generation != homeGeneration) return@withContext null
            if (next is Resource.Success) {
                next.value.filterNotNull().forEach { home ->
                    home.items.forEach { row ->
                        val filtered = context?.filterHomePageListByFilmQuality(row) ?: row
                        expandable[row.name]?.let { previous ->
                            expandable[row.name] = previous.copy(
                                list = previous.list.copy(
                                    list = (previous.list.list + filtered.list).distinctBy { it.apiName to it.url }
                                ),
                                currentPage = nextPage,
                                hasNext = home.hasNext,
                            )
                        }
                    }
                }
                // An explicit empty successful page is the end; a failed page remains retryable.
                if (next.value.filterNotNull().all { home -> home.items.none { it.name == name } }) {
                    expandable[name] = current.copy(hasNext = false)
                }
                publishPage()
            }
            expandable[name]
        } finally {
            lock -= request
        }
    }

    private fun publishPage() {
        _page.value = Resource.Success(expandable.mapValues { (_, row) ->
            row.copy(list = row.list.copy(list = row.list.list.toList()))
        })
    }

    private suspend fun loadDiscovery(
        source: APIRepository,
        forceRefresh: Boolean,
        generation: Int,
    ): Resource<List<HomePageResponse?>> = coroutineScope {
        expandable.clear()
        val permits = Semaphore(3)
        val responses = source.mainPage.mapIndexed { index, _ ->
            async {
                permits.withPermit {
                    val result = withContext(Dispatchers.IO) {
                        source.getMainPage(1, index, forceRefresh)
                    }
                    if (generation == homeGeneration && result is Resource.Success) {
                        result.value.filterNotNull().forEach { home ->
                            home.items.forEach { row ->
                                val filtered = context?.filterHomePageListByFilmQuality(row) ?: row
                                expandable[row.name] = ExpandableHomepageList(
                                    filtered.copy(list = filtered.list.distinctBy { it.apiName to it.url }),
                                    1, home.hasNext,
                                )
                            }
                        }
                        publishPage()
                    }
                    result
                }
            }
        }.awaitAll()
        if (responses.isNotEmpty() && responses.none { it is Resource.Success }) {
            Resource.Failure(false, "Unable to load your sources. Check your network and retry.")
        } else {
            Resource.Success(responses.flatMap { (it as? Resource.Success)?.value.orEmpty() })
        }
    }

    // this is soo over engineered, but idk how I can make it clean without making the main api harder to use :pensive:
    fun expand(name: String) = viewModelScope.launchSafe {
        expandAndReturn(name)
    }

    // returns the amount of items added and modifies current
    private suspend fun updatePreviewResponses(
        current: MutableList<LoadResponse>,
        alreadyAdded: MutableSet<String>,
        shuffledList: List<SearchResponse>,
        size: Int,
        source: APIRepository? = repo,
    ): Int {
        var count = 0

        val addItems = arrayListOf<SearchResponse>()
        for (searchResponse in shuffledList) {
            if (!alreadyAdded.contains(searchResponse.url)) {
                addItems.add(searchResponse)
                alreadyAdded.add(searchResponse.url)
                if (++count >= size) {
                    break
                }
            }
        }

        val add = addItems.amap { searchResponse ->
            val detailSource = if (source?.api === DiscoveryProvider) {
                getApiFromNameNull(searchResponse.apiName)?.let { APIRepository(it) }
            } else source
            withTimeoutOrNull(12_000L) { detailSource?.load(searchResponse.url) }
        }.mapNotNull { if (it != null && it is Resource.Success) it.value else null }
        current.addAll(add)
        return add.size
    }

    private var addJob: Job? = null
    fun loadMoreHomeScrollResponses() {
        if (addJob?.isActive == true || onGoingLoad?.isActive == true) return
        addJob = viewModelScope.launchSafe {
            val generation = homeGeneration
            val added = mutableListOf<LoadResponse>()
            val seen = previewResponsesAdded.toMutableSet()
            updatePreviewResponses(added, seen, currentShuffledList, 1)
            if (generation != homeGeneration) return@launchSafe
            previewResponses.addAll(added)
            previewResponsesAdded.addAll(seen)
            _preview.value = Resource.Success((previewResponsesAdded.size < currentShuffledList.size) to previewResponses.toList())
        }
    }

    private fun load(api: MainAPI, forceRefresh: Boolean): Job = viewModelScope.launchSafe {
        val generation = homeGeneration
        val source = APIRepository(api)
        repo = source

        _apiName.postValue(repo?.name)
        _randomItems.postValue(listOf())

        if (!source.hasMainPage) {
            _page.postValue(Resource.Success(emptyMap()))
            _preview.postValue(Resource.Failure(false, "No homepage"))
            isCurrentlyLoadingName = null
            return@launchSafe
        }


        _page.postValue(Resource.Loading())
        _preview.postValue(Resource.Loading())
        // cancel the current preview expand as that is no longer relevant
        addJob?.cancel()

        val data = if (api === DiscoveryProvider) {
            loadDiscovery(source, forceRefresh, generation)
        } else withContext(Dispatchers.IO) { source.getMainPage(1, forceRefresh = forceRefresh) }
        if (generation != homeGeneration) return@launchSafe
        when (data) {
            is Resource.Success -> {
                try {
                    if (api !== DiscoveryProvider) expandable.clear()
                    data.value.forEach { home ->
                        home?.items?.forEach { list ->
                            val filteredList =
                                context?.filterHomePageListByFilmQuality(list) ?: list
                            expandable[list.name] =
                                ExpandableHomepageList(
                                    filteredList.copy(
                                        list = filteredList.list.distinctBy { it.apiName to it.url }
                                    ), 1, home.hasNext
                                )
                        }
                    }

                    // Shelves must not wait for the slower detail requests used by the hero.
                    publishPage()

                    val items = data.value.mapNotNull { it?.items }.flatten()


                    previewResponses.clear()
                    previewResponsesAdded.clear()

                    //val home = data.value
                    if (items.isNotEmpty()) {
                        val currentList =
                            items.shuffled().filter { it.list.isNotEmpty() }
                                .flatMap { it.list }
                                .distinctBy { it.url }.toList()

                        if (currentList.isNotEmpty()) {
                            val randomItems =
                                context?.filterSearchResultByFilmQuality(currentList.shuffled())
                                    ?: currentList.shuffled()

                            val loadedPreviews = mutableListOf<LoadResponse>()
                            val loadedUrls = mutableSetOf<String>()
                            updatePreviewResponses(
                                loadedPreviews,
                                loadedUrls,
                                randomItems,
                                3,
                                source,
                            )
                            if (generation != homeGeneration) return@launchSafe
                            previewResponses.addAll(loadedPreviews)
                            previewResponsesAdded.addAll(loadedUrls)

                            _randomItems.postValue(randomItems)
                            currentShuffledList = randomItems
                        }
                    }
                    if (previewResponses.isEmpty()) {
                        _preview.postValue(
                            Resource.Failure(
                                false,
                                "No homepage responses"
                            )
                        )
                    } else {
                        _preview.value = Resource.Success((previewResponsesAdded.size < currentShuffledList.size) to previewResponses.toList())
                    }
                    publishPage()
                } catch (e: CancellationException) {
                    throw e
                } catch (e: Exception) {
                    _randomItems.postValue(emptyList())
                    logError(e)
                }
            }

            is Resource.Failure -> {
                @Suppress("UNNECESSARY_NOT_NULL_ASSERTION")
                _page.postValue(data!!)
                @Suppress("UNNECESSARY_NOT_NULL_ASSERTION")
                _preview.postValue(data!!)
            }

            else -> Unit
        }
        isCurrentlyLoadingName = null
    }

